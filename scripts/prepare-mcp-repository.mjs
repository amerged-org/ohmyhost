async function listFiles(directory, base = directory) {
  const files = [];
  for (const entry of await readdir(directory)) {
    const path = join(directory, entry);
    const stats = await lstat(path);
    if (stats.isDirectory()) files.push(...(await listFiles(path, base)));
    else if (stats.isFile()) files.push(relative(base, path).split(sep).join("/"));
    else throw new Error(`Unexpected archive path: ${relative(base, path)}`);
  }
  return files.sort();
}

export async function prepareMcpRepository({
  clone,
  version,
  sourceCommit,
  harnessSetup,
  catalog,
  npmRecord = null,
  tarball = null,
  fetch = globalThis.fetch,
  run = runCommand,
  now = () => new Date(),
}) {
  if (!VERSION.test(version)) throw new Error(`Invalid client version ${version}`);
  if (!COMMIT.test(sourceCommit ?? ""))
    throw new Error("The mirror requires the exact source commit");
  const git = async (...args) => (await run("git", args, { cwd: clone })).trim();

  if ((await git("rev-parse", "--show-toplevel")) !== (await realpath(clone)))
    throw new Error(`${clone} is not the top of a Git clone`);
  const origin = await git("remote", "get-url", "origin");
  if (!ORIGIN.test(origin))
    throw new Error(`Not a clone of amerged-org/ohmyhost-mcp: origin is ${origin}`);
  if ((await git("symbolic-ref", "--short", "HEAD")) !== "main")
    throw new Error(`The MCP mirror is committed on main; check out main in ${clone}`);
  if ((await git("status", "--porcelain=v1", "--untracked-files=all")) !== "")
    throw new Error("The MCP mirror clone has uncommitted changes; commit or discard them first");

  const releasePath = join(clone, "release.json");
  const previous = existsSync(releasePath) ? JSON.parse(await readFile(releasePath, "utf8")) : null;
  if (previous && compareVersions(previous.version, version) > 0)
    throw new Error(
      `The clone already mirrors ${previous.version}, newer than ${version}; a mirror never moves back`,
    );

  const readRegistry = async (path) => {
    const response = await fetch(`${REGISTRY}/${PACKAGE.replace("/", "%2F")}/${path}`, {
      redirect: "error",
    });
    if (!response.ok)
      throw new Error(`The registry answered ${response.status} for ${PACKAGE}@${path}`);
    return response.json();
  };
  const [metadata, latest] = await Promise.all([readRegistry(version), readRegistry("latest")]);
  if (latest.version !== version)
    throw new Error(
      `npm latest is ${latest.version}, not ${version}; the mirror follows the latest published version`,
    );
  if (
    metadata.name !== PACKAGE ||
    metadata.version !== version ||
    metadata.license !== "Apache-2.0" ||
    !String(metadata.dist?.integrity).startsWith("sha512-")
  )
    throw new Error(
      `The registry record of ${PACKAGE}@${version} is not the expected Apache-2.0 package`,
    );
  const tarballUrl = new URL(metadata.dist.tarball);
  if (tarballUrl.origin !== REGISTRY)
    throw new Error("The registry tarball URL is not on https://registry.npmjs.org");
  if (previous?.version === version && previous.npm?.integrity !== metadata.dist.integrity)
    throw new Error(`release.json records a different tarball for ${version}`);

  let bytes = tarball;
  if (!bytes) {
    const response = await fetch(tarballUrl, { redirect: "error" });
    if (!response.ok)
      throw new Error(`The registry answered ${response.status} for the ${version} tarball`);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  if (integrityOf(bytes) !== metadata.dist.integrity)
    throw new Error(`The tarball differs from the registry record of ${PACKAGE}@${version}`);
  const digest = sha256(bytes);
  if (npmRecord && (npmRecord.integrity !== metadata.dist.integrity || npmRecord.sha256 !== digest))
    throw new Error("The registry tarball differs from the prepared npm manifest");

  const stage = await mkdtemp(join(tmpdir(), "ohmyhost-mcp-mirror-"));
  try {
    const archive = join(stage, "package.tgz");
    await writeFile(archive, bytes);
    for (const entry of (await run("tar", ["-tzf", archive])).split("\n").filter(Boolean))
      if (!entry.startsWith("package/") || entry.split("/").includes("..") || entry.includes("\\"))
        throw new Error(`Unexpected archive path: ${entry}`);
    await mkdir(join(stage, "out"));
    await run("tar", ["-xzf", archive, "-C", join(stage, "out")]);
    const unpacked = join(stage, "out", "package");
    const files = await listFiles(unpacked);
    const tops = new Set(files.map((file) => file.split("/")[0]));
    const unexpected = [...tops].filter((top) => !TOP_LEVEL.has(top));
    if (unexpected.length > 0) throw new Error(`Unexpected archive path: ${unexpected.join(", ")}`);
    const missing = REQUIRED.filter((file) => !files.includes(file));
    if (missing.length > 0 || !tops.has("src"))
      throw new Error(
        `The MCP package lacks ${[...missing, ...(tops.has("src") ? [] : ["src"])].join(", ")}`,
      );
    const leaks = files.filter(
      (file) =>
        file.startsWith("src/") &&
        (!(PUBLIC_SOURCE.test(file) || BRIDGE_SOURCE.test(file)) ||
          /\.(?:node-)?test\./u.test(file) ||
          file.endsWith("/worker-main.ts")),
    );
    if (leaks.length > 0)
      throw new Error(
        `The npm tarball carries files outside the public MCP closure: ${leaks.join(", ")}; the mirror is refused`,
      );
    const bridgePrefix = `src/${OPTIONAL_WORKSPACE}/`;
    const hasBridge = files.some((file) => file.startsWith(bridgePrefix));
    if (hasBridge) {
      const absent = BRIDGE_REQUIRED.filter((file) => !files.includes(bridgePrefix + file));
      if (absent.length > 0)
        throw new Error(
          `The MCP package carries an incomplete ${OPTIONAL_WORKSPACE} closure; it lacks ${absent.join(", ")}`,
        );
    }
    for (const workspace of hasBridge
      ? [...PUBLIC_WORKSPACES, OPTIONAL_WORKSPACE]
      : PUBLIC_WORKSPACES) {
      const path = "src/" + workspace + "/package.json";
      if (!files.includes(path))
        throw new Error("The MCP package lacks public workspace metadata: " + path);
      const source = JSON.parse(await readFile(join(unpacked, path), "utf8"));
      if (
        source.name !== "@ohmyhost/" + workspace.split("/").at(-1) ||
        source.license !== "Apache-2.0" ||
        (workspace.startsWith("apps/") && source.version !== version)
      )
        throw new Error("Unexpected public workspace source package: " + path);
    }
    const manifest = JSON.parse(await readFile(join(unpacked, "package.json"), "utf8"));
    if (
      manifest.name !== PACKAGE ||
      manifest.version !== version ||
      manifest.license !== "Apache-2.0"
    )
      throw new Error(`The tarball's package.json is not ${PACKAGE}@${version} under Apache-2.0`);
    const readme = renderMcpReadme({ version, harnessSetup, catalog, postgresBridge: hasBridge });

    const omittedFiles = files.filter((file) => file.startsWith("dist/") || file === "README.md");
    const omitted = {};
    for (const file of omittedFiles) omitted[file] = sha256(await readFile(join(unpacked, file)));
    const unchanged =
      previous?.version === version && previous.npm?.integrity === metadata.dist.integrity;
    const release = {
      version,
      sourceCommit,
      npm: {
        name: PACKAGE,
        version,
        integrity: metadata.dist.integrity,
        sha256: digest,
        tarball: tarballUrl.href,
      },
      omitted,
      generatedAt: unchanged ? previous.generatedAt : now().toISOString(),
    };

    for (const path of OWNED) await rm(join(clone, path), { recursive: true, force: true });
    const mirrored = files.filter((file) => !omittedFiles.includes(file));
    for (const file of mirrored) {
      await mkdir(dirname(join(clone, file)), { recursive: true });
      await cp(join(unpacked, file), join(clone, file));
    }
    await writeFile(join(clone, "README.md"), readme);
    await writeFile(
      join(clone, "server.json"),
      `${JSON.stringify(renderServerJson({ version }), null, 2)}\n`,
    );
    await writeFile(releasePath, `${JSON.stringify(release, null, 2)}\n`);
    await mkdir(join(clone, ".github/workflows"), { recursive: true });
    await writeFile(
      join(clone, ".github/workflows/publish-registry.yml"),
      renderRegistryWorkflow(),
    );
    const changed = (await git("status", "--porcelain=v1", "--untracked-files=all")) !== "";
    return {
      clone,
      version,
      sourceCommit,
      integrity: metadata.dist.integrity,
      sha256: digest,
      mirrored: mirrored.length,
      omitted: omittedFiles.length,
      changed,
    };
  } finally {
    await rm(stage, { recursive: true, force: true });
  }
}

async function releaseSource(version) {
  const prepared = join(root, "docs/plan/tmp", `npm-${version}`, "manifest.json");
  if (existsSync(prepared)) {
    const manifest = JSON.parse(await readFile(prepared, "utf8"));
    return {
      sourceCommit: manifest.sourceCommit,
      npmRecord: manifest.packages.find((item) => item.name === PACKAGE) ?? null,
    };
  }
  const response = await globalThis.fetch(`https://ohmyho.st/releases/${version}/manifest.json`, {
    redirect: "error",
  });
  const manifest = response.ok ? await response.json() : null;
  if (manifest?.version !== version)
    throw new Error(
      `Cannot establish the source commit of ${version}: no docs/plan/tmp/npm-${version}/manifest.json and the live release is not ${version}`,
    );
  return { sourceCommit: manifest.source_commit, npmRecord: null };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const [clone, ...flags] = process.argv.slice(2);
  const options = {};
  for (let index = 0; index < flags.length; index += 2) {
    if (!["--version", "--tarball"].includes(flags[index]) || !flags[index + 1])
      throw new Error(
        "usage: prepare-mcp-repository.mjs <clone> [--version x.y.z] [--tarball path]",
      );
    options[flags[index].slice(2)] = flags[index + 1];
  }
  if (!clone)
    throw new Error("usage: prepare-mcp-repository.mjs <clone> [--version x.y.z] [--tarball path]");
  const version =
    options.version ??
    JSON.parse(await readFile(join(root, "apps/mcp/package.json"), "utf8")).version;
  const { sourceCommit, npmRecord } = await releaseSource(version);
  const catalog = JSON.parse(
    await runCommand(
      "git",
      ["show", `${sourceCommit}:apps/public-site/src/generated-mcp-tools.json`],
      { cwd: root },
    ),
  );
  const harnessSetup = await runCommand("git", ["show", `${sourceCommit}:${HARNESS_SETUP}`], {
    cwd: root,
  });
  const result = await prepareMcpRepository({
    clone: resolve(clone),
    version,
    sourceCommit,
    harnessSetup,
    catalog,
    npmRecord,
    tarball: options.tarball ? await readFile(resolve(options.tarball)) : null,
  });
  process.stdout.write(`${JSON.stringify(result)}\n`);
}
