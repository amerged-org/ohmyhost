#!/usr/bin/env node

import { lstat, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";

import { format } from "prettier";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const outputPath = resolve(packageRoot, "src/generated-skill-resources.ts");
const skillNames = Object.freeze([
  "ohmyhost-build-portable-app",
  "ohmyhost-migrate-supabase-postgres",
  "ohmyhost-get-started",
  "ohmyhost-deploy",
  "ohmyhost-deploy-github",
  "ohmyhost-domains-and-mail",
  "ohmyhost-manage-database",
  "ohmyhost-usage-and-budgets",
  "ohmyhost-troubleshoot-deployment",
  "ohmyhost-export-database",
]);
const includedTopLevelEntries = new Set(["SKILL.md", "references", "scripts"]);

const resources = [];
for (const skillName of skillNames) {
  const skillRoot = resolve(repositoryRoot, "skills", skillName);
  const skillMarkdown = await readFile(resolve(skillRoot, "SKILL.md"), "utf8");
  const metadata = parseFrontmatter(skillMarkdown, skillName);
  for (const absolutePath of await collectFiles(skillRoot)) {
    const relativePath = relative(skillRoot, absolutePath).split(sep).join("/");
    const [topLevel] = relativePath.split("/", 1);
    if (
      topLevel === undefined ||
      !includedTopLevelEntries.has(topLevel) ||
      relativePath.endsWith(".test.mjs")
    ) {
      continue;
    }
    const text = await readFile(absolutePath, "utf8");
    resources.push({
      skillName,
      relativePath,
      uri: `skill://ohmyhost/${skillName}/${relativePath}`,
      title: relativePath === "SKILL.md" ? metadata.name : `${metadata.name}: ${relativePath}`,
      description:
        relativePath === "SKILL.md"
          ? metadata.description
          : `Supporting resource for ${metadata.name}.`,
      mimeType: relativePath.endsWith(".md") ? "text/markdown" : "text/plain",
      text,
    });
  }
}
resources.sort((left, right) => (left.uri < right.uri ? -1 : left.uri > right.uri ? 1 : 0));

const generated = await format(
  [
    "// Generated by scripts/generate-skill-resources.mjs. Do not edit.",
    "export const GENERATED_SKILL_RESOURCES = Object.freeze(",
    `${JSON.stringify(resources, null, 2)} as const,`,
    ");",
    "",
  ].join("\n"),
  { parser: "typescript", printWidth: 100 },
);

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) fail("generated skill resources are stale");
} else {
  await writeFile(outputPath, generated, { encoding: "utf8", mode: 0o600 });
}

async function collectFiles(root) {
  const output = [];
  const entries = await readdir(root, { withFileTypes: true });
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = resolve(root, entry.name);
    const information = await lstat(path);
    if (information.isSymbolicLink()) fail(`symbolic links are forbidden: ${entry.name}`);
    if (information.isDirectory()) output.push(...(await collectFiles(path)));
    else if (information.isFile()) output.push(path);
    else fail(`special files are forbidden: ${entry.name}`);
  }
  return output;
}

function parseFrontmatter(markdown, expectedName) {
  const match = /^---\n([\s\S]*?)\n---\n/u.exec(markdown);
  if (!match) fail(`${expectedName} has no frontmatter`);
  const name = /^name:\s*([^\n]+)$/mu.exec(match[1])?.[1]?.trim();
  const description = /^description:\s*([^\n]+)$/mu.exec(match[1])?.[1]?.trim();
  if (name !== expectedName || !description) fail(`${expectedName} metadata is invalid`);
  return { name, description };
}

function fail(message) {
  throw new Error(`Agent skill generation failed: ${message}`);
}
